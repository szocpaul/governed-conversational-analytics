"""Artifact preservation tests (feature 006, T008/T009, spec US2).

The pre-upgrade (DSPy 3.2.1-era) measured artifacts are preserved under dated
`*-pre-006-YYYY-MM-DD.json` names before any re-measurement (FR-005). Naming
follows the feature 005 convention; the optimized program copy lives next to
its source per data-model.md.

Two invariants:
- At preservation time (T009) each copy was verified byte-identical to its
  source (SHA-256 recorded in specs/006-dspy-34-upgrade/verification-notes.md).
- Permanently (this test): the preserved copies are IMMUTABLE — their SHA-256
  must still match the values recorded at preservation time, even though the
  live sources (baseline.json, current.json, optimization-run.json,
  optimized_program.json) are legitimately regenerated by re-measurement and
  re-optimization and therefore differ from the preserved copies.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

# SHA-256 recorded at preservation time (T009, 2026-10-11); see
# specs/006-dspy-34-upgrade/verification-notes.md. These are the immutable
# pre-upgrade (DSPy 3.2.1) evidence copies.
PRESERVED = {
    "artifacts/baseline-pre-006-2026-10-11.json":
        "d58702e8a180616c0047f05ee1ec053ba522b8ef36ae80be3d0a6bc1429bb24b",
    "artifacts/current-pre-006-2026-10-11.json":
        "bfddd856f583be9d1103693b361552cb1198e3f01f31e96492086b186791f798",
    "artifacts/optimization-run-pre-006-2026-10-11.json":
        "a829bafc184e5c8fa5284d72ec7b7270a09a5b99e309fd391163bc5ed2ac4448",
    "app/ai/optimized_program-pre-006-2026-10-11.json":
        "421b664260b97ac9df3516111a28e7591ae2971d1207c285077dbe673e91f235",
}


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def test_preserved_copies_exist_and_are_immutable():
    missing = [rel for rel in PRESERVED if not (REPO / rel).exists()]
    assert not missing, f"preserved copies missing: {missing}"
    changed = {
        rel: (_sha256(REPO / rel), expected)
        for rel, expected in PRESERVED.items()
        if (REPO / rel).exists() and _sha256(REPO / rel) != expected
    }
    assert not changed, (
        "preserved pre-upgrade artifacts were modified after creation "
        f"(FR-005 violation): {changed}")
